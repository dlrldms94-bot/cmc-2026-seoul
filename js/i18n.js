const Locale = {
  key: "cmc-locale",
  current: "ko",

  init() {
    const saved = localStorage.getItem(this.key);
    this.current = saved === "en" || saved === "ko" ? saved : "ko";
    this.apply();
  },

  t(key) {
    return I18N[this.current][key] ?? I18N.ko[key] ?? key;
  },

  apply() {
    document.documentElement.lang = this.current === "en" ? "en" : "ko";
    document.documentElement.dataset.locale = this.current;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const value = this.t(key);
      if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = value;
      } else {
        el.textContent = value;
      }
    });

    document.querySelectorAll("[data-ko][data-en]").forEach((el) => {
      const value =
        this.current === "en"
          ? el.getAttribute("data-en")
          : el.getAttribute("data-ko");
      el.textContent = value ?? "";
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      el.setAttribute("aria-label", this.t(key));
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      el.setAttribute("title", this.t(key));
    });
  },

  toggle() {
    this.current = this.current === "ko" ? "en" : "ko";
    localStorage.setItem(this.key, this.current);
    this.apply();
  },
};
